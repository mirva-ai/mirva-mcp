#!/usr/bin/env node
/**
 * Writes packages/sdk/src/tools.generated.ts: one typed method per tool the server offers, its arguments typed from
 * the tool's input schema and documented with the tool's own descriptions.
 *
 *   MIRVA_URL=… MIRVA_API_KEY=… node tools/generate-tool-types.ts      the tool list of a running server
 *   node tools/generate-tool-types.ts tools.json                        a list saved as JSON (listTools' answer)
 *
 * The schemas use a subset of JSON Schema: type (one or a list), enum, properties, required, items, and
 * additionalProperties. Anything outside it is typed `unknown` rather than guessed.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { credentialsFromEnv, errorMessage, MirvaClient, type ToolDescriptor } from '../packages/sdk/src/client.ts';

const OUT = new URL('../packages/sdk/src/tools.generated.ts', import.meta.url);

interface Schema {
  type?: string | string[];
  enum?: unknown[];
  description?: string;
  properties?: Record<string, Schema>;
  required?: string[];
  items?: Schema;
  additionalProperties?: boolean | Schema;
  default?: unknown;
  minimum?: number;
  maximum?: number;
  maxItems?: number;
  maxLength?: number;
}

async function loadTools(file: string | undefined): Promise<ToolDescriptor[]> {
  if (file) return JSON.parse(readFileSync(file, 'utf8')) as ToolDescriptor[];
  const url = process.env.MIRVA_URL;
  if (!url) throw new Error('set MIRVA_URL and MIRVA_API_KEY, or pass a saved tool list');
  const client = new MirvaClient({ url, ...credentialsFromEnv() });
  try {
    return await client.call('listTools');
  } finally {
    client.close();
  }
}

/** A doc comment, indented, from a description and the constraints the type itself cannot state. */
function doc(schema: Schema, indent: string): string {
  const notes: string[] = [];
  if (schema.minimum !== undefined && schema.maximum !== undefined) notes.push(`${schema.minimum} to ${schema.maximum}.`);
  else if (schema.minimum !== undefined) notes.push(`At least ${schema.minimum}.`);
  else if (schema.maximum !== undefined) notes.push(`At most ${schema.maximum}.`);
  if (schema.maxItems !== undefined) notes.push(`At most ${schema.maxItems} items.`);
  if (schema.maxLength !== undefined) notes.push(`At most ${schema.maxLength} characters.`);
  if (schema.default !== undefined) notes.push(`Default ${JSON.stringify(schema.default)}.`);
  const text = [schema.description, ...notes].filter(Boolean).join(' ');
  if (!text) return '';
  // a description may contain */, which would end the comment
  return `${indent}/** ${text.replace(/\*\//g, '*\\/')} */\n`;
}

function typeOf(schema: Schema, indent: string): string {
  if (schema.enum) return schema.enum.map(v => JSON.stringify(v)).join(' | ');
  const types = Array.isArray(schema.type) ? schema.type : schema.type ? [schema.type] : [];
  if (!types.length) return 'unknown';
  return types.map(t => single(t, schema, indent)).join(' | ');
}

function single(type: string, schema: Schema, indent: string): string {
  switch (type) {
    case 'string': return 'string';
    case 'number':
    case 'integer': return 'number';
    case 'boolean': return 'boolean';
    case 'null': return 'null';
    case 'array': {
      const item = schema.items ? typeOf(schema.items, indent) : 'unknown';
      return /[|{]/.test(item) ? `Array<${item}>` : `${item}[]`;
    }
    case 'object': return objectType(schema, indent);
    default: return 'unknown';
  }
}

function objectType(schema: Schema, indent: string): string {
  const properties = Object.entries(schema.properties ?? {});
  const extra = schema.additionalProperties;
  if (!properties.length) {
    return typeof extra === 'object' ? `Record<string, ${typeOf(extra, indent)}>` : 'Record<string, unknown>';
  }
  const required = new Set(schema.required ?? []);
  const inner = `${indent}  `;
  const lines = properties.map(([name, property]) => {
    const key = /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name);
    return `${doc(property, inner)}${inner}${key}${required.has(name) ? '' : '?'}: ${typeOf(property, inner)};\n`;
  });
  return `{\n${lines.join('')}${indent}}`;
}

function method(tool: ToolDescriptor): string {
  const schema = tool.inputSchema as Schema;
  const hasRequired = (schema.required ?? []).length > 0;
  const args = typeOf({ ...schema, type: 'object' }, '  ');
  return `${doc({ description: tool.description }, '  ')}  ${tool.name}(args${hasRequired ? '' : '?'}: ${args}): Promise<ToolOutput>;\n`;
}

try {
  const tools = (await loadTools(process.argv[2])).slice().sort((a, b) => a.name.localeCompare(b.name));
  const source = `// Generated by tools/generate-tool-types.ts from the server's tool list; regenerate rather than edit.

import type { ToolOutput } from './output.ts';

/** The tools the server offered when this file was generated, one method each. */
export interface MirvaTools {
${tools.map(method).join('\n')}}

/** The names of those tools. */
export type MirvaToolName = keyof MirvaTools;
`;
  writeFileSync(OUT, source);
  console.log(`wrote ${tools.length} tools to ${OUT.pathname}`);
} catch (e) {
  console.error(`generate-tool-types: ${errorMessage(e)}`);
  process.exit(1);
}
